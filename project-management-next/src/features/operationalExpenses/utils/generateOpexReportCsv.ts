import { toFormattedDate, type CompanySettingsLike } from '@/features/jobCards/utils/pdfBranding'
import { downloadCsvFile, formatMoney } from '@/lib/export-csv'

const statusLabel = (s: string) => {
  if (s === 'APPROVED' || s === 'PAYMENT_PROCESSED') return 'Posted'
  if (s === 'APPROVED_ACCOUNTANT') return 'Awaiting Mgr'
  return s || 'Pending'
}

export const generateOpexReportCsv = async (
  expenses: any[],
  dateRange: { from: string; to: string } | null,
  companySettings?: CompanySettingsLike,
  generatedBy?: string
) => {
  const rows: string[][] = []

  if (companySettings?.companyName) {
    rows.push([companySettings.companyName.toUpperCase()])
    if (companySettings.address) rows.push([companySettings.address])
    rows.push([''])
  }

  rows.push(['OPERATIONAL EXPENSES REPORT'])
  const rangeText =
    dateRange?.from && dateRange?.to ? `${dateRange.from} to ${dateRange.to}` : 'All Time'
  rows.push(['Period', rangeText])
  rows.push(['Generated', new Date().toLocaleDateString()])
  rows.push(['Generated By', generatedBy || 'System User'])
  rows.push([''])

  const totalAll = expenses.reduce((s, e) => s + (Number(e.amount) || 0), 0)
  rows.push(['SUMMARY'])
  rows.push(['Total Expenses', String(expenses.length)])
  rows.push(['Total Amount', `$${formatMoney(totalAll)}`])
  rows.push([''])

  rows.push(['#', 'Date', 'Category', 'Description / Beneficiary', 'Dept', 'Method', 'Status', 'Amount', 'Requester'])

  expenses.forEach((exp, i) => {
    rows.push([
      String(i + 1),
      toFormattedDate(exp.createdAt || new Date()),
      (exp.category || '—').toUpperCase(),
      exp.title || exp.description || '—',
      exp.department || '—',
      (exp.paymentMethod || '—').toUpperCase(),
      statusLabel(exp.status || ''),
      `$${formatMoney(exp.amount || 0)}`,
      exp.createdByName || exp.requesterName || '—',
    ])
  })

  const fromStr = dateRange?.from?.replace(/\//g, '-') || 'all'
  const toStr = dateRange?.to?.replace(/\//g, '-') || 'time'
  downloadCsvFile(rows, `OPEX_Report_${fromStr}_to_${toStr}.csv`)
}
