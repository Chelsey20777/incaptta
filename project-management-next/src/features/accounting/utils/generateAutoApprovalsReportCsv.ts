import { downloadCsvFile, formatMoney } from '@/lib/export-csv'
import { autoApprovalRuleLabel } from '@/lib/job-card-expense-approval'

function approvedByLabel(item: any): string {
  const raw = item.accountantApprovedBy
  if (typeof raw === 'object' && raw) {
    return raw.displayName || raw.name || raw.email || '—'
  }
  return raw || '—'
}

function categoryLabel(e: any): string {
  if (e.category === 'job-card-expense') return 'Ad-hoc'
  return String(e.category || e.title || 'Opex').replace(/-/g, ' ')
}

function formatWhen(e: any): string {
  const d =
    e.accountantApprovedAt?.toDate?.() ||
    e.createdAt?.toDate?.() ||
    (e.createdAt ? new Date(e.createdAt) : new Date())
  return d.toLocaleString()
}

export const generateAutoApprovalsReportCsv = async (
  expenses: any[],
  activeTab: string,
  searchQuery: string,
  companySettings?: { companyName?: string; address?: string },
  generatedBy?: string
) => {
  const rows: string[][] = []
  if (companySettings?.companyName) {
    rows.push([companySettings.companyName.toUpperCase()])
    if (companySettings.address) rows.push([companySettings.address])
    rows.push([''])
  }

  rows.push(['AUTO-APPROVALS AUDIT TRAIL REPORT'])
  rows.push(['View Group', activeTab.toUpperCase()])
  if (searchQuery) rows.push(['Search', searchQuery])
  rows.push(['Generated', new Date().toLocaleString()])
  rows.push(['Generated By', generatedBy || 'System User'])
  rows.push([''])

  const totalValue = expenses.reduce((s, e) => s + Math.abs(Number(e.amount || 0)), 0)
  rows.push(['SUMMARY'])
  rows.push(['Total Auto-Approved', String(expenses.length)])
  rows.push(['Total Bypassed Value', `$${formatMoney(totalValue)}`])
  rows.push(['Rule', 'Job-card ad-hoc < $200; other eligible Opex < $300'])
  rows.push([''])

  rows.push(['#', 'Date & Time', 'Type', 'Description', 'Approved By', 'Amount', 'Rule'])
  expenses.forEach((item, idx) => {
    rows.push([
      String(idx + 1),
      formatWhen(item),
      categoryLabel(item),
      item.description || item.title || '—',
      approvedByLabel(item),
      `$${formatMoney(Math.abs(Number(item.amount || 0)))}`,
      autoApprovalRuleLabel(item),
    ])
  })

  downloadCsvFile(rows, `AutoApprovals_Audit_${new Date().toISOString().slice(0, 10)}.csv`)
}
