import { toFormattedDate, type CompanySettingsLike } from '@/features/jobCards/utils/pdfBranding'
import { downloadCsvFile, formatMoney } from '@/lib/export-csv'

export const generateLedgerReportCsv = async (
  entries: any[],
  accountLabel: string,
  dateRange: { from: string; to: string } | null,
  companySettings?: CompanySettingsLike,
  generatedBy?: string
) => {
  const rows: string[][] = []
  const fmtAbs = (n: number) =>
    Math.abs(Number(n || 0)).toLocaleString(undefined, {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })

  if (companySettings?.companyName) {
    rows.push([companySettings.companyName.toUpperCase()])
    if (companySettings.address) rows.push([companySettings.address])
    if (companySettings.phone || companySettings.email) {
      rows.push([
        `${companySettings.phone || ''} ${companySettings.email ? '| ' + companySettings.email : ''}`,
      ])
    }
    if (companySettings.website) rows.push([companySettings.website])
    rows.push([''])
  }

  rows.push(['LEDGER REPORT'])
  rows.push(['Account', accountLabel])
  const rangeText =
    dateRange?.from && dateRange?.to ? `${dateRange.from} to ${dateRange.to}` : 'All Time'
  rows.push(['Period', rangeText])
  rows.push(['Generated', new Date().toLocaleDateString()])
  rows.push(['Generated By', generatedBy || 'System User'])
  rows.push([''])

  const totalIn = entries.filter((e) => e.amount > 0).reduce((s, e) => s + e.amount, 0)
  const totalOut = entries.filter((e) => e.amount < 0).reduce((s, e) => s + Math.abs(e.amount), 0)
  const net = totalIn - totalOut
  const closing =
    entries.length > 0
      ? (entries[entries.length - 1].balance ?? entries[entries.length - 1].globalBalance ?? 0)
      : 0

  rows.push(['SUMMARY'])
  rows.push(['Total Credits', `+$${fmtAbs(totalIn)}`])
  rows.push(['Total Debits', `-$${fmtAbs(totalOut)}`])
  rows.push(['Net Movement', `${net >= 0 ? '+' : '-'}$${fmtAbs(net)}`])
  rows.push(['Closing Balance', `$${formatMoney(closing)}`])
  rows.push([''])

  rows.push(['#', 'Date', 'Account', 'Description', 'Type', 'Amount', 'Running Balance'])

  entries.forEach((e, i) => {
    rows.push([
      String(i + 1),
      e.date || toFormattedDate(e.createdAt || new Date()),
      e.account || '—',
      e.description || '—',
      e.type || '—',
      `${e.amount >= 0 ? '+' : '-'}$${fmtAbs(e.amount)}`,
      `$${formatMoney(e.balance ?? e.globalBalance ?? 0)}`,
    ])
  })

  const acctSlug = accountLabel.replace(/\s+/g, '_').toLowerCase()
  const fromStr = dateRange?.from?.replace(/\//g, '-') || 'all'
  const toStr = dateRange?.to?.replace(/\//g, '-') || 'time'
  downloadCsvFile(rows, `Ledger_${acctSlug}_${fromStr}_to_${toStr}.csv`)
}
