import { toFormattedDate, type CompanySettingsLike } from '@/features/jobCards/utils/pdfBranding'
import { downloadCsvFile, formatMoney } from '@/lib/export-csv'

export const generateTransfersReportCsv = async (
  transfers: any[],
  companySettings?: CompanySettingsLike,
  generatedBy?: string
) => {
  const rows: string[][] = []

  if (companySettings?.companyName) {
    rows.push([companySettings.companyName.toUpperCase()])
    if (companySettings.address) rows.push([companySettings.address])
    rows.push([''])
  }

  rows.push(['FUND TRANSFERS REPORT'])
  rows.push(['Generated', new Date().toLocaleDateString()])
  rows.push(['Generated By', generatedBy || 'System User'])
  rows.push([''])

  const total = transfers.reduce((s, t) => s + (Number(t.amount) || 0), 0)
  rows.push(['SUMMARY'])
  rows.push(['Total Transfers', String(transfers.length)])
  rows.push(['Total Amount', `$${formatMoney(total)}`])
  rows.push([''])

  rows.push(['#', 'Date', 'From', 'To', 'Amount', 'Status', 'Reference', 'Description', 'Initiated By'])

  transfers.forEach((t, i) => {
    rows.push([
      String(i + 1),
      t.date || toFormattedDate(t.createdAt || new Date()),
      t.fromAccount || '—',
      t.toAccount || '—',
      `$${formatMoney(t.amount || 0)}`,
      t.status || 'PENDING_ACCOUNTANT',
      t.reference || '—',
      t.description || '—',
      t.initiatedByName || t.createdByName || t.initiatedByEmail || '—',
    ])
  })

  downloadCsvFile(rows, `Transfers_Report_${new Date().toISOString().slice(0, 10)}.csv`)
}
