import { toFormattedDate, type CompanySettingsLike } from '@/features/jobCards/utils/pdfBranding'

/**
 * Escapes a cell value for CSV encoding
 */
function escapeCsvValue(val: any): string {
    if (val === null || val === undefined) return ''
    const str = String(val)
    if (str.includes(',') || str.includes('"') || str.includes('\n')) {
        return `"${str.replace(/"/g, '""')}"`
    }
    return str
}

const fmt = (n: number) =>
    Math.abs(Number(n || 0)).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })

export const generateLedgerReportCsv = async (
    entries: any[],
    accountLabel: string,
    dateRange: { from: string; to: string } | null,
    companySettings?: CompanySettingsLike,
    generatedBy?: string
) => {
    const rows: string[][] = []

    // ── Branding Section ─────────────────────────────────────────────
    if (companySettings?.companyName) {
        rows.push([companySettings.companyName.toUpperCase()])
        if (companySettings.address) rows.push([companySettings.address])
        if (companySettings.phone || companySettings.email) {
            rows.push([`${companySettings.phone || ''} ${companySettings.email ? '| ' + companySettings.email : ''}`])
        }
        if (companySettings.website) rows.push([companySettings.website])
        rows.push(['']) // Spacer
    }

    // ── Header / Info ────────────────────────────────────────────────
    rows.push(['LEDGER REPORT'])
    rows.push(['Account', accountLabel])
    const rangeText = dateRange?.from && dateRange?.to
        ? `${dateRange.from} to ${dateRange.to}`
        : 'All Time'
    rows.push(['Period', rangeText])
    rows.push(['Generated', new Date().toLocaleDateString()])
    rows.push(['Generated By', generatedBy || 'System User'])
    rows.push(['']) // Spacer

    // ── Summary ──────────────────────────────────────────────────────
    const totalIn  = entries.filter(e => e.amount > 0).reduce((s, e) => s + e.amount, 0)
    const totalOut = entries.filter(e => e.amount < 0).reduce((s, e) => s + Math.abs(e.amount), 0)
    const net      = totalIn - totalOut
    const closing  = entries.length > 0 ? (entries[entries.length - 1].balance ?? entries[entries.length - 1].globalBalance ?? 0) : 0

    rows.push(['SUMMARY'])
    rows.push(['Total Credits', `+$${fmt(totalIn)}` || '0.00'])
    rows.push(['Total Debits', `-$${fmt(totalOut)}` || '0.00'])
    rows.push(['Net Movement', `${net >= 0 ? '+' : '-'}$${fmt(net)}` || '0.00'])
    rows.push(['Closing Balance', `$${fmt(closing)}` || '0.00'])
    rows.push(['']) // Spacer

    // ── Transaction detail ──────────────────────────────────────────
    rows.push(['#', 'Date', 'Account', 'Description', 'Type', 'Amount', 'Running Balance'])

    entries.forEach((e, i) => {
        rows.push([
            String(i + 1),
            e.date || toFormattedDate(e.createdAt || new Date()),
            e.account || '—',
            e.description || '—',
            e.type || '—',
            `${e.amount >= 0 ? '+' : '-'}$${fmt(e.amount)}`,
            `$${fmt(e.balance ?? e.globalBalance ?? 0)}`
        ])
    })

    // Convert to CSV blob
    const csvContent = rows.map(r => r.map(escapeCsvValue).join(',')).join('\n')
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' })

    // Download File
    const acctSlug = accountLabel.replace(/\s+/g, '_').toLowerCase()
    const fromStr  = dateRange?.from?.replace(/\//g, '-') || 'all'
    const toStr    = dateRange?.to?.replace(/\//g, '-')   || 'time'
    
    const fileName = `Ledger_${acctSlug}_${fromStr}_to_${toStr}.csv`
    
    const link = document.createElement('a')
    const url = URL.createObjectURL(blob)
    link.setAttribute('href', url)
    link.setAttribute('download', fileName)
    link.style.visibility = 'hidden'
    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
}
