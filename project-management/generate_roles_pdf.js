
import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import fs from 'fs';

const doc = new jsPDF();

// Helper for colors
const PRIMARY_COLOR = [234, 88, 12]; // Orange-600
const TEXT_DARK = [31, 41, 55];

// Title
doc.setFontSize(22);
doc.setTextColor(...PRIMARY_COLOR);
doc.text('IncapttaPro Role Permissions Summary', 105, 20, { align: 'center' });

doc.setDrawColor(...PRIMARY_COLOR);
doc.setLineWidth(0.5);
doc.line(20, 25, 190, 25);

// User Assignments Section
doc.setFontSize(14);
doc.setTextColor(...TEXT_DARK);
doc.text('Current User Assignments', 20, 35);

const userHeaders = [['Name', 'Email', 'Role']];
const userData = [
    ['Kganya Dube', 'kdube@incaptta.co.zw', 'TECHNICAL'],
    ['Emeldah Muzhewe', 'muzheweemelder@gmail.com', 'ACCOUNTANT'],
    ['Farai Mufambisi', 'admin2@incaptta.co.zw', 'MANAGER']
];

autoTable(doc, {
    startY: 40,
    head: userHeaders,
    body: userData,
    theme: 'grid',
    headStyles: { fillColor: PRIMARY_COLOR },
    margin: { left: 20, right: 20 }
});

// Permissions Matrix
doc.setFontSize(14);
const matrixY = doc.lastAutoTable.finalY + 15;
doc.text('Permission Matrix', 20, matrixY);

const permHeaders = [['Feature', 'Technical', 'Accountant', 'Manager', 'Admin']];
const permData = [
    ['Create Job Card', 'Yes', 'Yes', 'No', 'Yes'],
    ['Approve Job Card', 'No', 'Lvl 1', 'Final', 'Full'],
    ['CRM Access', 'Yes', 'Yes', 'Yes', 'Yes'],
    ['Create OPEX', 'Yes', 'Yes', 'Yes', 'Yes'],
    ['Approve OPEX', 'No', 'Yes', 'Yes', 'Yes'],
    ['Initiate Transfer', 'No', 'Yes', 'No', 'Yes'],
    ['Approve Transfer', 'No', 'No', 'Yes', 'Yes'],
    ['Ledger View', 'No', 'Yes', 'Yes', 'Yes'],
    ['Inventory View', 'No', 'No', 'Yes', 'Yes'],
    ['Admin Panel', 'No', 'No', 'No', 'Yes']
];

autoTable(doc, {
    startY: matrixY + 5,
    head: permHeaders,
    body: permData,
    theme: 'striped',
    headStyles: { fillColor: TEXT_DARK },
    margin: { left: 20, right: 20 },
    columnStyles: {
        1: { halign: 'center' },
        2: { halign: 'center' },
        3: { halign: 'center' },
        4: { halign: 'center' }
    }
});

// Roles Description
const descY = (doc).lastAutoTable.finalY + 15;
doc.setFontSize(14);
doc.text('Role Descriptions', 20, descY);

doc.setFontSize(10);
doc.setTextColor(80, 80, 80);
const descriptions = [
    { name: 'Admin/Super Admin:', desc: 'Full system control. Manages users, system settings, and is the ultimate authority for all approvals and data corrections.' },
    { name: 'Manager:', desc: 'Operational lead. Approves fund transfers, finalizes job cards, and manages inventory levels.' },
    { name: 'Accountant:', desc: 'Financial officer. Initiates fund transfers, performs level 1 job card approvals, and reconciles the ledger.' },
    { name: 'Technical:', desc: 'Field team. Responsible for creating job cards and recording field expenses for approval.' }
];

let currentY = descY + 8;
descriptions.forEach(role => {
    doc.setFont('helvetica', 'bold');
    doc.text(role.name, 20, currentY);
    doc.setFont('helvetica', 'normal');
    const splitDesc = doc.splitTextToSize(role.desc, 150);
    doc.text(splitDesc, 45, currentY);
    currentY += (splitDesc.length * 5) + 2;
});

// Footer
doc.setFontSize(8);
doc.setTextColor(150, 150, 150);
doc.text('Generated by IncapttaPro System - ' + new Date().toLocaleString(), 105, 285, { align: 'center' });

const pdfOutput = doc.output('arraybuffer');
fs.writeFileSync('Roles_Summary.pdf', Buffer.from(pdfOutput));
console.log('PDF generated: Roles_Summary.pdf');
